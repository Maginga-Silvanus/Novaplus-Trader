@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PrivacySettingsScreen(
    onBackClick: () -> Unit,
    modifier: Modifier = Modifier
) {
    var allowAnalytics by remember { mutableStateOf(true) }
    var allowPersonalization by remember { mutableStateOf(true) }
    var allowMarketing by remember { mutableStateOf(false) }

    Box(
        modifier = modifier
            .fillMaxSize()
            .background(BackgroundDark)
    ) {
        Column(modifier = Modifier.fillMaxSize()) {
            // Top Bar
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp, vertical = 12.dp),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                IconActionButton(
                    icon = Icons.AutoMirrored.Filled.ArrowBack,
                    contentDescription = "Back",
                    onClick = onBackClick
                )

                Text(
                    text = "Privacy & Data Settings",
                    color = TextPrimary,
                    fontSize = 18.sp,
                    fontWeight = FontWeight.Bold
                )

                Box(modifier = Modifier.padding(start = 24.dp))
            }

            LazyColumn(
                modifier = Modifier.fillMaxSize(),
                contentPadding = PaddingValues(bottom = 100.dp, start = 16.dp, end = 16.dp),
                verticalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                item {
                    Text(
                        text = "PRIVACY PREFERENCES",
                        color = TextMuted,
                        fontSize = 11.sp,
                        fontWeight = FontWeight.Bold,
                        letterSpacing = 1.sp
                    )
                }

                item {
                    SecurityCard(
                        title = "Analytics & Performance Data",
                        subtitle = "Help improve app responsiveness and crash reporting",
                        isEnabled = allowAnalytics,
                        onToggle = { allowAnalytics = it }
                    )
                }

                item {
                    SecurityCard(
                        title = "Personalized App Experience",
                        subtitle = "Tailor market suggestions based on trading activity",
                        isEnabled = allowPersonalization,
                        onToggle = { allowPersonalization = it }
                    )
                }

                item {
                    SecurityCard(
                        title = "Marketing & Promotional News",
                        subtitle = "Receive news about new feature updates and offers",
                        isEnabled = allowMarketing,
                        onToggle = { allowMarketing = it }
                    )
                }

                item {
                    Spacer(modifier = Modifier.height(10.dp))
                    Column(
                        modifier = Modifier
                            .fillMaxWidth()
                            .clip(RoundedCornerShape(16.dp))
                            .background(SurfaceDarkElevated)
                            .border(1.dp, SurfaceBorder, RoundedCornerShape(16.dp))
                            .padding(14.dp)
                    ) {
                        Text(
                            text = "DATA COMPLIANCE NOTICE",
                            color = ElectricLime,
                            fontSize = 11.sp,
                            fontWeight = FontWeight.Bold,
                            letterSpacing = 0.8.sp
                        )
                        Spacer(modifier = Modifier.height(4.dp))
                        Text(
                            text = "Your financial transaction history and ledger records are processed strictly according to banking regulations and privacy laws. NovaPlus Trader never sells personal financial data to third-party advertisers.",
                            color = TextMuted,
                            fontSize = 11.sp,
                            lineHeight = 16.sp
                        )
                    }
                }
            }
        }
    }
}
